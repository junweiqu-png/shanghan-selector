const esc=s=>String(s??"").replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
function resolve(title,text,offset,annotation){
 const exact=Number.isInteger(offset)&&offset>=0?window.WENYAN_COMPLETE_TRANSLATIONS?.lookup(title,text,offset):null;
 const a=exact||annotation;
 return a?.meaning&&a.code!=="proper-name"&&!/专名/.test(a.pos||"")?a:null;
}
function phraseAt(text,offset,phrase){for(let start=text.indexOf(phrase);start>=0;start=text.indexOf(phrase,start+1))if(offset>=start&&offset<start+phrase.length)return true;return false;}
function word(title,text,offset,annotation){
 const a=resolve(title,text,offset,annotation);if(!a||[...String(a.term||"")].length!==1)return [];
 for(const [phrase,test,correct,wrong,work]of phrases)if(Number.isInteger(offset)&&phrase.includes(a.term)&&phraseAt(text,offset,phrase)&&(title===work||test.test(a.meaning)))return [{label:phrase,correct,wrong}];
 const sense=a.meaning.split(/，指|；指|，这里|；这里/)[0];
 const entry=rules[a.term]?.find(([test])=>test.test(sense));
 if(!entry)return [];
 const atoms=sense.split(/[，、；]/).map(x=>x.trim());
 const wrong=entry[1].filter(value=>!atoms.includes(value)).slice(0,3);
 return wrong.length?[{label:a.term,correct:a.meaning,wrong}]:[];
}
function sentence(title,text,annotation,options={}){
 const out=[],seen=new Set(),covered=[];
 function offer(item){const key=item.label+"|"+item.correct+"|"+item.wrong.join("|");if(!seen.has(key)&&!options.omitLabels?.includes(item.label)){seen.add(key);out.push(item);}}
 for(const [phrase,,correct,wrong,work]of phrases){
  if(!text.includes(phrase))continue;
  // Compound alerts need a classroom anchor or an explicitly corresponding gloss.
  if(title!==work&&!(annotation?.term&&phrase.includes(annotation.term)&&phrases.find(p=>p[0]===phrase)[1].test(annotation.meaning||"")))continue;
  offer({label:phrase,correct,wrong});let start=text.indexOf(phrase);while(start>=0){covered.push([start,start+phrase.length]);start=text.indexOf(phrase,start+1);}
 }
 for(const [fragment,correct,wrong]of sentences)if(text.includes(fragment))offer({label:fragment,correct,wrong});
 for(let offset=0;!options.skipWords&&offset<text.length;offset++){
  if(!/\p{Script=Han}/u.test(text[offset])||covered.some(([start,end])=>offset>=start&&offset<end))continue;
  const unique=annotation?.term===text[offset]&&text.indexOf(text[offset])===text.lastIndexOf(text[offset])?annotation:null;
  for(const item of word(title,text,offset,unique))offer(item);
 }
 return out;
}
