import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const window={},requested=[];
const manifest={files:[],large:{available:true,indexEncoding:'json',termIndexEncoding:'json',termIndexShards:64,indexShards:64}};
const stableHash=s=>{let h=2166136261;for(let i=0;i<s.length;i++){h^=s.charCodeAt(i);h=Math.imul(h,16777619);}return h>>>0;};
const termShard=(stableHash('筑')%64).toString().padStart(2,'0');
const fallbackShard=('龘'.codePointAt(0)%64).toString().padStart(2,'0');
const termPayload={筑:[{source:'《扩展古籍测试》',chapter:'卷一',text:'某篇古文记载筑墙之事。',id:'fixture-001',group:'经史名言',matched:'筑',matchType:'exact'}]};
const fallbackPayload={龘:[{source:'《偏字古籍测试》',chapter:'卷二',text:'古文中亦见龘字。',id:'fixture-002',group:'二十四史及古籍'}]};
const bytesFor=x=>{const b=Buffer.from(JSON.stringify(x),'utf8');return b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength);};
const fetch=async url=>{
 requested.push(String(url));
 if(String(url).includes('expanded-manifest.json'))return {ok:true,json:async()=>manifest};
 if(String(url).endsWith('/catalog.json'))return {ok:true,json:async()=>({entries:[]})};
 if(String(url).includes('large-term-index/'+termShard+'.json?v=20261112fullcorpus1'))return {ok:true,arrayBuffer:async()=>bytesFor(termPayload)};
 if(String(url).includes('large-term-index/')&&String(url).endsWith('.json?v=20261112fullcorpus1'))return {ok:true,arrayBuffer:async()=>bytesFor({})};
 if(String(url).includes('large-index/'+fallbackShard+'.json?v=20261112fullcorpus1'))return {ok:true,arrayBuffer:async()=>bytesFor(fallbackPayload)};
 return {ok:false,status:404};
};
const document={getElementById:()=>null,addEventListener:()=>{},querySelectorAll:()=>[]};
const context=vm.createContext({window,document,localStorage:{getItem:()=>null,setItem:()=>{}},fetch,TextDecoder,Uint8Array,Promise,JSON,Array,Map,Object,Set,String,Number,Math,Blob,Response,DecompressionStream});
vm.runInContext(fs.readFileSync('wenyan/study-editor.js','utf8'),context,{filename:'study-editor.js'});
const rows=await window.WENYAN_STUDY_EDITOR.searchClassics('筑');
assert.equal(rows.length,1);
assert.equal(rows[0].title,'《扩展古籍测试》·卷一');
assert.equal(rows[0].text,'某篇古文记载筑墙之事。');
assert.equal(rows[0].group,'经史名言');
assert(!Object.hasOwn(rows[0],'translation'),'raw full-text hits must not invent translations');
assert(requested.some(url=>url.includes('large-term-index/'+termShard+'.json?v=20261112fullcorpus1')),'published single-character terms must use the expanded term index');
const fallback=await window.WENYAN_STUDY_EDITOR.searchClassics('龘');
assert.equal(fallback.length,1);
assert.equal(fallback[0].title,'《偏字古籍测试》·卷二');
assert(requested.some(url=>url.includes('large-index/'+fallbackShard+'.json?v=20261112fullcorpus1')),'unlisted single characters must fall back to the full character index');
console.log(JSON.stringify({ok:true,term:'筑',termIndex:rows.length,rareCharacterFallback:fallback.length,translationInvented:false}));
